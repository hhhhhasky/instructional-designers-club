你有没有遇到过这样的备课时刻：教材已经翻开，课文、例题、活动和练习都摆在面前，你却不知道到底该把什么当作重点？于是，你可能先去网上找一份教案，或者在课标里搜索教材课题的名称，希望找到一句可以直接放进教学设计里的话。但搜索的结果往往不理想：有时根本找不到同名表述，有时能找到很多相关文字，却仍然不知道这一课究竟该教到什么程度。

问题不一定出在你没有读课标，而可能出在你一开始就把课标当成了另一种教材，甚至当成了一本现成教案。这节课，我们先把三个容易混在一起的对象分清：课标、教材和教案。

课程标准，是国家对某一学段、某一学科课程作出的纲领性规定。它关心的不是明天上午第二节课要提哪三个问题，而是这门课程为什么存在、学生在一个学段中需要学习哪些内容、最终大体要形成怎样的表现。也就是说，课标提供的是课程的基本方向、内容范围和质量要求。

教材承担的是另一项工作。它依据课标，把这些比较宏观的要求转化为具体的课文、例题、实验、图表、问题和练习。你可以把教材理解为课标落地的重要载体。但“教材里出现了”不等于“它自动就是这个单元的核心”。教材中的一幅图可能只是帮助理解的材料，一道练习可能承担巩固作用，一个知识点也可能只是为了支持更重要的能力发展。它们究竟处在什么位置，仍然需要课标提供判断尺度。

教案则更具体。教案面对的是你眼前这一群学生，是一节课有限的时间，是学生已经知道什么、可能在哪里卡住，以及你准备怎样组织学习。它是教师结合课标要求、教材内容和真实学情作出的教学安排。因此，课标不能直接复制成教案，教材目录也不能直接变成教学目标。

现在，请跟着我走一遍备课时真正有用的思考过程。假如我打开七年级英语 Animal Friends 单元，看到动物名称、对话、信息卡、说明文和项目活动，我不会马上决定每一页怎样讲。我会先问自己：“国家课程为什么要让七年级学生学习这一组内容？学完这个单元，学生只是多记住几个动物单词，还是要能够获取和组织动物信息、表达喜好与理由、理解动物与人类生活的关系，并提出关爱行动？”带着这些问题，我再进入对应级别的课程目标、课程内容和学业质量。课标在这里不是给我一个现成答案，而是在帮助我建立判断答案的尺度。

再看另一种常见写法：“课标强调核心素养，所以本单元要落实全部核心素养。”这句话听起来没有错，却几乎不能指导备课。它没有告诉我们是哪个学段的具体表现，没有说明教材中的什么内容能够承载，也没有指出学生要做出什么可观察的行为。如果一句课标分析不能帮助你判断哪些内容更重要、学生要学到什么程度，那么它很可能只是正确的口号，还没有成为真正的分析。

所以，这节课你只需要牢牢记住一组关系：课标提供尺度，教材提供载体，教案作出行动选择。以后再打开教材时，不妨先暂停一下，不急着问“这一页怎么教”，而先问：“课标为什么要求学生在这个学段学习这类内容？最终希望他们形成什么表现？”当这个问题开始影响你对教材重点的判断时，课标才真正进入了备课。
