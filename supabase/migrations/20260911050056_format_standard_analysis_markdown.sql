### 回到本单元最初的问题

现在，请暂时放下前面六节课中的案例，回到你最初可能遇到的那个问题：面对一份课标和一个教材单元，我到底应该从哪里开始，又应该得到什么结果？如果你能够独立回答这个问题，课标分析的方法才真正属于你。

### 第一步：抓准对标对象

整个过程的起点不是搜索，而是抓准对标对象。你先阅读教材目录、单元导语和主要任务，把一个单元压缩成主题与核心要素。这样做，是因为课标通常以学段、领域、主题或任务群规定一段学习的发展方向，而不是为每一个课题准备同名句子。先单元、后单课，是我们进入课标时最重要的尺度意识。

### 第二步：完成三部分定位

带着主题和核心要素，你依次阅读三个部分。课程目标帮助你找到本学段的素养终点，但不能只停在宏观的核心素养名称，还要继续读到子维度和具体学段表现；课程内容帮助你判断主要教什么、需要经历怎样的学习，但必须顺着本学科真实的目录结构查找；学业质量呈现学段结束时的综合表现，用来检查你确定的单元方向是否过窄或过浅。三个部分各有功能，不能只读其中一个，也不能互相替代。

### 第三步：用四个维度精准解读

找到相关条目后，你再用四个问题把它读透：学生要做什么？对什么知识对象做？在什么情境、材料或支持下做？做到什么程度？这就是认知动词、知识名词、应用条件和学习程度四个维度。它们不是四个必须填满的格子，而是帮助你避免两种误读：既不要把“解释、分析、判断”降成知识记忆，也不要把“运用、探究、设计”无限拔高成超出学段和单元承载能力的复杂任务。

### 第四步：用三道筛子做取舍

接下来，你需要做一次有依据的取舍。每一条候选内容都要接受三个追问：它是否与单元核心要素直接相关？删掉后会不会改变我对单元方向的判断？教材是否能够持续、实质地承载？强相关内容进入报告，中相关内容谨慎保留并注明范围，低相关内容删除。分析能力往往不体现在你留下了多少，而体现在你为什么留下这些、又为什么舍弃那些。

### 第五步：形成可回溯的报告

最后，你把结果写进单元课标分析报告。报告先用版本、学段、章节路径和原文证明“找得准”，再用差异化的四维解读证明“读得透”，然后把分散证据综合为单元方向和教学重点线索。写完后还要反向检查：结论中的每一个关键词能不能回到原文，能不能找到解读依据，能不能在教材中找到承载。能够完成这次反查，报告才真正闭环。

> **本单元方法链：**++先抓准单元对象，再完成三部分定位，用四个维度精准解读，用三道筛子做取舍，最后形成可回溯的单元方向和教学重点线索。++

确定单元方向之后，我们才回到教材内部，判断不同单课分别承担铺垫、形成、深化还是应用的作用，而不是让每一课重复承担整个单元的全部要求。

### 记住课标分析的边界

还要记住本单元的边界。课标分析可以告诉你课程为什么这样要求、这个单元应当指向哪里、教材中什么值得重点关注，却不能直接替你决定某一种教学流程，也不能替代教材分析、学情分析、目标撰写、活动设计和评价设计。你现在完成的是后续设计的上位依据，而不是整份教案。

