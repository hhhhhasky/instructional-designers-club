### 目录不同，方法还成立吗

学到这里，你已经掌握了课标分析的两个核心动作：**先定位，再解读**。但当你真正换到自己的学科时，新的困惑可能出现了。为什么数学课标要先进入“图形与几何”，语文课标却要判断学习任务群？为什么英语要面对六个课程内容要素，生物学又能在一个学习主题下连续看到内容要求、学业要求和教学提示？如果目录结构完全不同，我们前面学的方法还成立吗？

> **答案是：**++查找路径会变，判断逻辑不会变。++

无论你教哪一门学科，都要先用课程目标找到对应学段的终点，再沿这门学科自己的目录结构找到课程内容，然后用学业质量校准综合表现，最后做减法，只留下真正能够改变单元方向的依据。

这节课不会要求你从头到尾线性读完五个长案例。你可以在页面下方先选择一个最接近自己任教学科的分支，观察专家怎样作出判断；读完后，再切换到一个相对陌生的学科，检查自己能否只根据目录结构还原分析路径。你学习的不是五个案例的结论，而是结论背后那套稳定的思考动作。

### 五个学科，五条目录路径

#### 生物学：在主题板块中连续阅读三类要求

假如你选择生物学，会看到一种“主题板块内连续呈现三类要求”的结构。面对七年级下册“植物的生活”，我先从课程目标中判断，生命观念里的物质与能量观、基于证据的科学思维和探究实践，与这个单元存在持续承载。然后进入课程内容中的“植物的生活”主题，把内容要求、学业要求和教学提示放在一起阅读。我不会只摘种子萌发、蒸腾作用、光合作用这些名词，而会继续寻找“解释、阐明、设计、探究”等行为，以及生产生活和实验探究的条件。最后，学业质量把这些内容放回真实问题情境。三个部分连起来，单元方向才从零散知识变成“理解生命过程与物质能量关系，运用知识解释实际现象，并以证据探究影响因素”。

#### 数学：沿内容领域找到推理主线

如果你选择数学，入口会发生变化。分析八年级“全等三角形”时，我会先锁定第四学段，再进入初中“图形与几何—图形的性质—三角形”。内容要求确实列出了若干全等判定事实，但学业要求和教学提示反复出现“得到、验证、证明、逻辑和推理”。这时我会作出一个关键判断：**SAS、ASA、SSS 不是三句等待背诵的口诀，而是学生学习如何从条件推出结论、如何用依据表达判断的载体。**因此，单元方向应当指向“条件—结论—依据—表达”的推理主线。至于同属图形与几何的圆、坐标和图形变化，因为不能解释这个单元为什么这样学，就不应被一起装进报告。

#### 道德与法治：先锁定学段，再进入教育主题

如果你选择道德与法治，需要先锁定学段，再进入教育主题。面对“维护社会秩序”，我先把教材压缩成“秩序—规则—道德—法律—行动”，再进入道德修养、法治观念和责任意识的第四学段表现。为什么不把五项核心素养全部抄下来？因为我要检查三课是否都有持续、可见的内容承载。接着，我会在第四学段的道德教育和法治教育中，筛选与公共秩序、社会公德、遵纪守法和依法办事直接相关的内容。这样得到的不是一句宽泛的“落实法治观念”，而是一条能够解释三课关系的单元方向。

#### 语文：把学段目标与学习任务群交叉起来

如果你选择语文，课程目标和课程内容的组织方式需要交叉起来看。分析九年级“思辨与创造”单元时，我不会搜索每篇课文的标题，而会带着“观点、材料、论证、质疑和有依据表达”进入第四学段目标，再进入发展型学习任务群中的“思辨性阅读与表达”。当课程目标提出“区分观点与材料、发现二者联系并作出判断”，任务群强调比较、推断、质疑和重证据表达，学业质量进一步要求“解释观点与材料的联系”，三处就形成了一条清楚的进阶线：**从区分，到解释，再到有依据的判断与表达。**

#### 英语：在主题统领下连接六类内容要素

如果你选择英语，第一步不是查动物词汇和语法，而是先进入四项核心素养各子素养的三级要求。面对 Animal Friends，我会带着“获取和组织动物信息、表达喜好理由、理解动物与文化及生态的关系、提出保护行动”等核心要素，判断哪些三级表现能够被教材真实承载。之后，再进入三级课程内容，用教材里的对话、信息卡、帖子、说明文和项目任务筛选主题、语篇、语言知识、文化知识、语言技能和学习策略。这样，what、where、why、because 和名词复数会回到它们应有的位置：**它们是完成介绍、解释和判断的语言支撑，不是单元学习的终点。**

五条路径看起来不同，但你应该已经发现，专家一直在重复同样的判断：我现在要找的是终点、内容还是综合表现？这条依据是否真的与单元核心要素直接相关？它能不能改变我对单元方向的判断？教材是否能够持续、实质地承载它？

### 用三道筛子完成取舍

这最后三个问题，就是内容取舍的三道筛子。直接决定单元方向、核心内容或学习深度的，属于**强相关**，应当进入报告；能够解释上位方向、但本单元只能部分承载的，属于**中相关**，可以在必要时简要保留并注明范围；只有宽泛联系、删掉也不影响判断的，属于**低相关**，应当删除。++做减法并不是忽视课标，而是在保护真正重要的信息不被淹没。++

所以，当你切换不同学科案例时，请不要记忆每个案例摘了哪一句。你真正要带走的是：目录告诉你从哪里进入，三部分告诉你分别寻找什么，三道筛子帮助你决定最后留下什么。路径随学科变化，判断逻辑始终稳定。
