### 先回答一个最前置的问题

作为本单元课标分析的第一课，我们先来回答第一个最前置的问题：为什么要阅读课标、分析课标？我猜在很多老师平时上课的时候，很少看课标，更多是看教材和教参。大家会觉得课标特别抽象、特别宏观，它定义的是六年、三年、九年学完后学生应呈现的样子。与这一个单元、这一节课、这四十分钟的颗粒度相比，课标显得太宏观了，它怎么指导我这一节课四十分钟该如何教学呢？所以老师们就很少去看课标。那么，我们看课标的目的是什么呢？这就是我们这节课首先要回答的问题。如果这一关没搞清楚，大家对于后续的学习都无从谈起。

> **本课核心问题：**++课标究竟怎样改变一位教师的备课判断？++

### 从教学设计框架看课标的作用

好，我们首先从教学设计整个的框架角度来分析这个问题。也就是说，当你从零到一研发一节课、一份教案时，课标对你的备课以及整个框架有什么影响？首先，课标的一个很大作用是帮助我们去制定教学目标。你说你这节课的目标确立要有依据，那依据来自哪里呢？其中一个依据就来自于课标。你到底要教完这个单元、这些课后，希望把学生送到哪里？这个最权威的依据来自课标，也是最不容置疑的。这是第一点。

第二，课标的核心作用是帮助你去研读教材。很多老师习惯“教教材”，但其实教材只是落实课标的一种手段。教材只不过是把情境、问题、案例、任务、活动、题目、例题、练习整合到了一本书里。所有这些环节的目的，都是为了落实课标。所以，我们有很多不同的教材，甚至我们可以用找到的例子、题目去替换教材内容吗？完全可以。教材只是提供了教学资源，它不是唯一的资源，也不是落实课标唯一的手段，对不对？所以，当我们拿到这本教材时，怎么去理解教材的重点是什么？到底我们要教的是什么？我们只是为了教这两页纸吗？不是。教这两页纸的目的是为了达成课标对于该阶段学生培养的需求。课标定义的是学生最终应该成为什么样子，课标是课程的“北极星”和大方向，教材只是实现这个大方向的一种手段或核心手段。所以，阅读课标能更好地帮助你去校准对教材的理解。如果你教教材的重点理解偏颇，从某种意义上来说，课标可以帮助你平衡。

> **两项直接作用：**课标既帮助我们**制定教学目标**，也帮助我们**研读并校准教材重点**。

