### 为什么搜索到了，还不算找到了

现在，我们正式进入课标分析的方法。第一步叫作“定位准确”，它要解决的不是你有没有打开课标，而是你读到的内容究竟是不是这个单元真正需要的内容。

很多教师一打开课标就按下搜索键，把教材课题名称输入进去。这个动作看起来高效，却常常让人走错方向。课标通常按学段、内容领域、学习主题或任务群组织，它不会为教材里的每一课、每一篇课文、每一道例题分别准备一句同名要求。你搜索不到，不代表课标没有要求；搜索到了相同词语，也不代表那一段就适用于你的单元。

### 第一步：先把教材单元“压缩”一下

所以，在搜索之前，你需要先把教材单元“压缩”一下。请打开目录、单元导语和主要学习任务，连续问自己三个问题：**这个单元主要讨论什么主题或大概念？围绕这个主题，学生主要要认识、理解或者处理什么问题？哪些核心概念、关键能力、典型任务或价值议题反复出现？**

例如，面对一个议论性文章单元，与其拿每篇课文的标题去搜索，不如把它压缩成“观点、材料、论证、质疑和有依据的表达”；面对“全等三角形”单元，可以提炼出“判定条件、几何推理和有依据的表达”；面对“维护社会秩序”，可以抓住“秩序、规则、道德、法律和行动”。这些词不是为了在课标中逐字命中，而是你判断一段课标是否真正相关的线索。

### 第二步：依次进入课标三个部分

#### 课程目标：找到学段终点

有了这组线索，接下来要依次进入课标的三个部分。第一个部分是**课程目标**，它回答的是“这一阶段最终要把学生带向哪里”。这里最容易犯的错误，是看到“语言能力、思维能力、法治观念、推理能力”等核心素养名称就停止。核心素养名称更像地图上的大区域，不是单元定位的终点。我会继续往下读它的子维度和对应学段表现，然后拿刚才提炼的单元核心要素逐项检验：“这个单元真的能让学生出现这种表现吗？教材中有没有持续的内容和任务来承载？”只有经得起这两个追问的内容，才值得保留。

#### 课程内容：找到内容载体

第二个部分是**课程内容**，它回答“围绕这个方向主要教什么”。这时不要急着全文搜索，而要先观察本学科课标自己的目录结构。假如我分析道德与法治，我会先锁定学段，再进入对应教育主题；分析数学，我会先区分小学或初中，再进入数与代数、图形与几何等内容领域及相应学段；分析语文，我要先判断主要学习任务群，再读取这个任务群中的对应学段内容；分析英语，则要进入相应级别，在主题统领下联系语篇、语言知识、文化知识、语言技能和学习策略。历史、生物学等学科常按内容板块或学习主题组织，需要在同一板块中联系阅读内容要求、学业要求和教学提示。

这里没有一条适用于所有学科的机械搜索路线。真正稳定的做法是：++先看目录，确认这门学科用什么作为索引轴，再顺着它进入相关位置。++某些课标没有在单元层级单列“学业要求”，那就如实记录“未单列”，而不是为了填满表格去虚构一段文字。

#### 学业质量：校准综合表现

第三个部分是**学业质量**。它描述学生完成一个学段学习后的综合表现，可以理解为一幅较远的“终点图景”。我进入本学段的学业质量后，不会整段复制，而会带着单元核心要素去找：学生要在什么类型的情境中表现所学？要综合运用哪些知识、方法或素养？与这个单元最接近的表现是什么，大致要达到什么程度？学业质量的作用是检查我们确定的单元方向是否过窄、过浅，而不是把整个学段的要求变成一节课的测试题。

走完这三个部分，你应该能够用两句话说清定位结果：“这个单元在本学段主要指向什么？围绕这一方向，它主要通过什么内容，帮助学生逐步形成什么表现？”如果这两句话还说不出来，说明你可能只是找到了若干段文字，还没有完成定位。

### 最后：完成四次核对

最后，不要忘记做四次核对。我通常会从头检查：**课标版本、学科和学段是否正确；摘录所在章节及适用范围是否正确；它与单元核心要素是真的直接相关，还是只有词语相似；章节路径或页码是否记录完整，另一个人能不能回到同一处原文。**完成这四次核对，才算真正解决了“读没读到”的问题。下一步，我们才有资格讨论：这些已经找对的句子，究竟有没有被读透。
