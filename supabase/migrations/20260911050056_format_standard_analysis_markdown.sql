### 这节课要回答什么

上一节课，我们讲了为什么需要分析课标。面对这样一份抽象、宏观、看起来离日常授课比较远的文本，这节课我们继续回答：**到底什么是课程标准？截至 2026 年，我们使用的课标发生了哪些变化？**

理解这些问题，需要先认识课标的整体构成。下面，我们先从 2022 年版各学科课程标准的基本结构入手。

### 2022 年版课标的六个核心部分

#### 1. 课程性质

它回答：**这到底是一门什么课？**

它告诉你，这门课程最核心的学科属性和育人价值是什么。

#### 2. 课程理念

它回答：**这门课应该坚持什么基本方向？**

比如，课程应该怎样组织，怎样理解学生学习，应该重视什么。

#### 3. 课程目标

它回答：**学生最终应该发展成什么样？**

这里会进入各个学科自己的核心素养目标。

#### 4. 课程内容

它回答：**到底学什么？**

其中包括内容组织和具体要求等。

#### 5. 学业质量

它回答：**一个阶段走完以后，学生学到什么程度才算达到要求？**

#### 6. 课程实施

它回答：**前面的目标和内容，最后怎样进入教学、评价、教材和资源？**

### 把六个部分压缩成三个层次

这六个部分还可以进一步压缩成三个层次：

1. **为什么教、最终培养什么？**——课程性质、课程理念、课程目标。
2. **具体学什么、最终学成什么？**——课程内容、学业质量。
3. **怎样实施？**——课程实施。

这样一看，是不是突然简单了很多？它们不是六个散乱的概念，而是在从上到下依次回答：

> **课标的基本逻辑：**++为什么教 → 教什么 → 学成什么 → 怎么做。++

