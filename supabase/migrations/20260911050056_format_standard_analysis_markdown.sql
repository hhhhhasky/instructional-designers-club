#### 日常课：用评价反查课标要求

我们先从日常课来看。日常课老师们不太去看课标，因为觉得太抽象、太宏观。但是，对于有升学需求的老师来说，比如中考、高考，我们很大程度上要“以评定教”，也就是看评价是怎么考的，进而倒推实际上的教学重点和难点。考试的试题该怎么命题、怎么定制？是以教材还是课标来定制？它最大、最核心的标准是以课标为基准，所以它一定不会超出课标的范畴。因此，我们在教日常课时，完全可以拿考试试题和课标进行对齐，看一看题目是怎么考察的，进而思考在教学当中如何落实对应的课标要求。所以，这是对我们日常课赋能的一种手段。

