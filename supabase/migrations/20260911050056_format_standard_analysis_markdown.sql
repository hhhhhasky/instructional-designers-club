在 2022 年版课标中，我认为与一线教师最相关的一个变化，是它开始更努力地把这些层次连接起来。

尤其是在课程内容部分，你会反复看到三个概念：

- **内容要求**
- **学业要求**
- **教学提示**

同时，课标还增加了非常重要的**学业质量标准**。

